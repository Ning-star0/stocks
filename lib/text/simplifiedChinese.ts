export function toSimplifiedChinese(value: string) {
  let output = value;
  for (const [traditional, simplified] of phraseMap) {
    output = output.split(traditional).join(simplified);
  }
  return output.replace(/[\u3400-\u9fff]/g, (char) => charMap[char] ?? char);
}

export function containsCjk(value: string) {
  return /[\u3400-\u9fff]/.test(value);
}

export function needsSimplifiedChineseSummary(value?: string | null) {
  const text = value?.trim();
  if (!text) return false;
  return !containsCjk(text) || toSimplifiedChinese(text) !== text;
}
